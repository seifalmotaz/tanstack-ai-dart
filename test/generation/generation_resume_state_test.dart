import 'dart:convert';

import 'package:tanstack_ai_dart/connections.dart';
import 'package:tanstack_ai_dart/generation.dart';
import 'package:test/test.dart';

import 'test_support.dart';

const artifactRef = PersistedArtifactRef(
  role: 'output',
  artifactId: 'artifact-1',
  threadId: 'thread-1',
  runId: 'run-1',
  name: 'image.png',
  mimeType: 'image/png',
  size: 1234,
  createdAt: '2026-07-06T00:00:00.000Z',
  source: PersistedArtifactSource(
    activity: 'image',
    path: 'thread-1/run-1/image.png',
    provider: 'test',
    model: 'image-model',
    mediaType: 'image',
  ),
);

GenerationResumeSnapshot reduceChunks(
  List<StreamChunk> chunks, {
  GenerationResumeSnapshot? initial,
}) {
  GenerationResumeSnapshot? snapshot = initial;
  for (final chunk in chunks) {
    snapshot = updateGenerationResumeSnapshot(snapshot, chunk);
  }
  return snapshot!;
}

void main() {
  group('generation resume state reducer', () {
    test('tracks thread and run from persisted generation events', () {
      final snapshot = reduceChunks([
        {
          'type': 'RUN_STARTED',
          'threadId': 'thread-1',
          'runId': 'run-1',
          'timestamp': 1,
        },
        custom(
          GenerationEvents.progress,
          {'progress': 50, 'message': 'Halfway'},
          threadId: 'thread-1',
          runId: 'run-1',
        ),
      ]);

      expect(snapshot.resumeState?.threadId, 'thread-1');
      expect(snapshot.resumeState?.runId, 'run-1');
      expect(snapshot.status, GenerationResumeStatus.running);
      expect(snapshot.lastEvent?.type, 'CUSTOM');
      expect(snapshot.lastEvent?.name, GenerationEvents.progress);
    });

    test('stores generation artifacts as persisted refs only', () {
      final snapshot = reduceChunks([
        custom(
          GenerationEvents.artifacts,
          [
            artifactRef.toJson(),
            {
              'b64Json': 'raw-media-bytes',
              'url': 'data:image/png;base64,raw-media-bytes',
            },
          ],
          threadId: 'thread-1',
          runId: 'run-1',
        ),
      ]);

      expect(snapshot.pendingArtifacts, equals([artifactRef]));
      expect(jsonEncode(snapshot.toJson()), isNot(contains('raw-media-bytes')));
      expect(snapshot.activity, 'image');
    });

    test('sanitizes artifact refs before storing them in resume snapshots', () {
      final unsafeArtifactRef = {
        ...artifactRef.toJson(),
        'sourceUrl': 'data:image/png;base64,raw-artifact-bytes',
        'b64Json': 'raw-artifact-bytes',
        'url': 'https://example.com/${'x' * 4096}',
        'source': {
          ...artifactRef.source.toJson(),
          'extraRawField': 'raw-artifact-bytes',
        },
      };

      final snapshot = reduceChunks([
        custom(
          GenerationEvents.artifacts,
          [unsafeArtifactRef],
          threadId: 'thread-1',
          runId: 'run-1',
        ),
        custom(
          GenerationEvents.result,
          {
            'id': 'result-1',
            'artifacts': [unsafeArtifactRef],
          },
          threadId: 'thread-1',
          runId: 'run-1',
        ),
      ]);

      expect(snapshot.pendingArtifacts, equals([artifactRef]));
      expect(snapshot.result?.artifacts, equals([artifactRef]));
      final encoded = jsonEncode(snapshot.toJson());
      expect(encoded, isNot(contains('raw-artifact-bytes')));
      expect(encoded, isNot(contains('b64Json')));
      expect(encoded, isNot(contains('extraRawField')));
    });

    test('stores terminal result metadata without raw generated bytes', () {
      final snapshot = reduceChunks([
        custom(
          GenerationEvents.result,
          {
            'id': 'result-1',
            'model': 'image-model',
            'images': [
              {
                'b64Json': 'raw-image-bytes',
                'url': 'data:image/png;base64,raw-image-bytes',
                'revisedPrompt': 'clean prompt',
              },
            ],
            'artifacts': [artifactRef.toJson()],
          },
          threadId: 'thread-1',
          runId: 'run-1',
        ),
        runFinished('run-1'),
      ]);

      expect(snapshot.resumeState, isNull);
      expect(snapshot.status, GenerationResumeStatus.complete);
      expect(snapshot.result?.id, 'result-1');
      expect(snapshot.result?.model, 'image-model');
      expect(snapshot.result?.artifacts, equals([artifactRef]));
      expect(jsonEncode(snapshot.toJson()), isNot(contains('raw-image-bytes')));
      expect(jsonEncode(snapshot.toJson()), isNot(contains('b64Json')));
    });

    test(
        'keeps a durable artifact sourceUrl and strips non-durable or oversized ones',
        () {
      const durableUrl = 'https://cdn.example.com/artifacts/image.png';
      final durable = reduceChunks([
        custom(
          GenerationEvents.artifacts,
          [
            {...artifactRef.toJson(), 'sourceUrl': durableUrl}
          ],
          threadId: 'thread-1',
          runId: 'run-1',
        ),
      ]);
      expect(durable.pendingArtifacts?.first.sourceUrl, durableUrl);

      final unsafeUrls = [
        'data:image/png;base64,raw-image-bytes',
        'blob:https://example.com/raw-image-bytes',
        'https://example.com/${'x' * 4096}',
        'not a url',
      ];
      for (final sourceUrl in unsafeUrls) {
        final snapshot = reduceChunks([
          custom(
            GenerationEvents.artifacts,
            [
              {...artifactRef.toJson(), 'sourceUrl': sourceUrl}
            ],
            threadId: 'thread-1',
            runId: 'run-1',
          ),
        ]);
        expect(snapshot.pendingArtifacts, equals([artifactRef]));
        expect(snapshot.pendingArtifacts?.first.sourceUrl, isNull);
      }
    });

    test(
        'clears resume state and stores lightweight error metadata on terminal errors',
        () {
      final snapshot = reduceChunks([
        {
          'type': 'RUN_STARTED',
          'threadId': 'thread-1',
          'runId': 'run-1',
          'timestamp': 1,
        },
        {
          'type': 'RUN_ERROR',
          'threadId': 'thread-1',
          'runId': 'run-1',
          'message': 'Generation failed',
          'code': 'provider_error',
          'error': {'message': 'legacy message'},
          'timestamp': 2,
        },
      ]);

      expect(snapshot.resumeState, isNull);
      expect(snapshot.status, GenerationResumeStatus.error);
      expect(snapshot.error?.message, 'Generation failed');
      expect(snapshot.error?.code, 'provider_error');
    });

    test(
        'captures the video job id from video:job:created before any result arrives',
        () {
      final snapshot = reduceChunks([
        {
          'type': 'RUN_STARTED',
          'threadId': 'thread-1',
          'runId': 'run-1',
          'timestamp': 1,
        },
        custom(
          GenerationEvents.videoJobCreated,
          {'jobId': 'job-42'},
          threadId: 'thread-1',
          runId: 'run-1',
        ),
      ]);

      expect(snapshot.status, GenerationResumeStatus.running);
      expect(snapshot.result?.providerJobId, 'job-42');
    });

    test('merges an initial seed and lets later run events update it', () {
      const seed = GenerationResumeSnapshot(
        resumeState: null,
        status: GenerationResumeStatus.error,
        error: GenerationErrorSnapshot(message: 'previous failure'),
        pendingArtifacts: [artifactRef],
      );

      final midRun = reduceChunks(
        [
          custom(
            GenerationEvents.progress,
            {'progress': 10},
            threadId: 'thread-1',
            runId: 'run-2',
          ),
        ],
        initial: seed,
      );

      expect(midRun.resumeState?.runId, 'run-2');
      expect(midRun.error?.message, 'previous failure');
      expect(midRun.pendingArtifacts, equals([artifactRef]));
    });

    test('drops stale error, result, and artifacts when a new run starts', () {
      const seed = GenerationResumeSnapshot(
        resumeState: null,
        status: GenerationResumeStatus.error,
        error: GenerationErrorSnapshot(message: 'previous failure'),
        result: GenerationResultSnapshot(id: 'old-result'),
        pendingArtifacts: [artifactRef],
      );

      final snapshot = reduceChunks(
        [
          {
            'type': 'RUN_STARTED',
            'threadId': 'thread-1',
            'runId': 'run-2',
            'timestamp': 1,
          },
        ],
        initial: seed,
      );

      expect(snapshot.status, GenerationResumeStatus.running);
      expect(snapshot.resumeState?.threadId, 'thread-1');
      expect(snapshot.resumeState?.runId, 'run-2');
      expect(snapshot.error, isNull);
      expect(snapshot.result, isNull);
      expect(snapshot.pendingArtifacts, isNull);
    });
  });

  group('parseGenerationResumeSnapshot', () {
    test(
        'round-trips a reducer-produced snapshot through JSON, dropping lastEvent',
        () {
      final produced = reduceChunks([
        {
          'type': 'RUN_STARTED',
          'threadId': 'thread-1',
          'runId': 'run-1',
          'timestamp': 1,
        },
        custom(
          GenerationEvents.result,
          {
            'id': 'result-1',
            'model': 'image-model',
            'artifacts': [artifactRef.toJson()],
          },
          threadId: 'thread-1',
          runId: 'run-1',
        ),
        runFinished('run-1'),
      ]);

      final parsed = parseGenerationResumeSnapshot(
        jsonDecode(jsonEncode(produced.toJson())),
      );
      expect(parsed, isNotNull);
      expect(parsed!.status, GenerationResumeStatus.complete);
      expect(parsed.resumeState, isNull);
      expect(parsed.result?.toJson(), equals(produced.result?.toJson()));
      expect(parsed.lastEvent, isNull);
    });

    test(
        'rejects garbage, invalid statuses, malformed resume state, and future schema versions',
        () {
      expect(parseGenerationResumeSnapshot(null), isNull);
      expect(parseGenerationResumeSnapshot('running'), isNull);
      expect(parseGenerationResumeSnapshot({}), isNull);
      expect(
        parseGenerationResumeSnapshot(
          {'resumeState': null, 'status': 'paused'},
        ),
        isNull,
      );
      expect(
        parseGenerationResumeSnapshot(
          {
            'resumeState': {'threadId': 'thread-1'},
            'status': 'running',
          },
        ),
        isNull,
      );
      expect(
        parseGenerationResumeSnapshot(
          {'schemaVersion': 2, 'resumeState': null, 'status': 'idle'},
        ),
        isNull,
      );
    });

    test('strips unknown fields and re-validates artifact refs from storage',
        () {
      final parsed = parseGenerationResumeSnapshot({
        'resumeState': {'threadId': 'thread-1', 'runId': 'run-1'},
        'status': 'running',
        'pendingArtifacts': [
          artifactRef.toJson(),
          {'b64Json': 'raw-bytes'},
        ],
        'error': {'message': 'boom', 'code': 'E1', 'extra': 'dropped'},
        'injected': 'dropped',
      });

      expect(parsed, isNotNull);
      expect(parsed!.pendingArtifacts, equals([artifactRef]));
      expect(parsed.error?.message, 'boom');
      expect(parsed.error?.code, 'E1');
      final encoded = jsonEncode(parsed.toJson());
      expect(encoded, isNot(contains('raw-bytes')));
      expect(encoded, isNot(contains('dropped')));
    });
  });
}
